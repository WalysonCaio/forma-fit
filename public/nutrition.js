export const normalizeFoodText=s=>String(s||'').normalize('NFD').replace(/[\u0300-\u036f]/g,'').toLowerCase().trim();
export function parseFoodText(text,catalog=foodCatalog){return String(text).split(/\n|;|\s+\+\s+/).filter(x=>x.trim()).map(text=>{let normalized=normalizeFoodText(text),quantity=null,grams=null;const amount=normalized.match(/(\d+(?:[.,]\d+)?)\s*(kg|gramas?|g|unidades?|un\b)?/);if(amount){quantity=Number(amount[1].replace(',','.'));if(amount[2]==='kg')grams=quantity*1000;else if(/^(g|grama)/.test(amount[2]||''))grams=quantity;normalized=normalized.replace(amount[0],'').replace(/^\s*(de|do|da)\s+/,'').trim();}let candidates=catalog.filter(f=>[f.name,...(f.aliases||[])].some(a=>normalizeFoodText(a)===normalized));if(!candidates.length)candidates=catalog.filter(f=>[f.name,...(f.aliases||[])].some(a=>{const n=normalizeFoodText(a);return normalized===n||normalized.startsWith(n+' ')&&n.length>3&&/^(cozid[oa]s?|grelhad[oa]s?|cru[as]?|em flocos)$/.test(normalized.slice(n.length+1));}));candidates.sort((a,b)=>normalizeFoodText(b.name).length-normalizeFoodText(a.name).length);const food=candidates[0];if(food&&grams===null&&quantity!==null&&food.unit_g)grams=quantity*food.unit_g;const mismatched=/(frit|cru|cozid|grelhad)/.exec(normalized)?.[0];const exact=food&&normalizeFoodText(food.name)===normalized;const prepConflict=food&&mismatched&&!normalizeFoodText(food.name).includes(mismatched);return {food_id:food&&!prepConflict?food.id:'',grams,original:text.trim(),needs_review:!exact||grams===null,problem:!food||prepConflict?'Escolha o alimento e preparo':grams===null?'Informe o peso em gramas':''};});}
export function mealNutrition(ingredients,catalog=foodCatalog){const total={kcal:0,protein:0,carbs:0,fat:0,complete:true};if(!Array.isArray(ingredients)||!ingredients.length)return {...total,complete:false};for(const i of ingredients){const f=i.food_snapshot||catalog.find(f=>f.id===i.food_id);if(!f||!Number.isFinite(i.grams)||i.grams<=0){total.complete=false;continue;}for(const k of ['kcal','protein','carbs','fat'])total[k]+=f[k]*i.grams/100;}return total;}
